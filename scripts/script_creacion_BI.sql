CREATE VIEW LOS_SELECTOS.GANANCIA_POR_CANAL_DE_VENTA_POR_MES
AS
	SELECT
		T.TIEMPO_ANIO,
		T.TIEMPO_MES,
		CV.CANAL_NOMBRE,
		SUM(HVP.PRODUCTO_PRECIO_TOTAL) AS TOTAL_VENTAS,
		SUM(HCP.PRODUCTO_CANTIDAD*HCP.PRODUCTO_PRECIO_UNITARIO) AS TOTAL_COMPRAS,
		(SELECT SUM(VENTA_PERIODICIDAD.MEDIO_DE_PAGO_COSTO)
				FROM (SELECT MDP.MEDIO_DE_PAGO_COSTO
						FROM LOS_SELECTOS.BI_HECHO_VENTA_PRODUCTO VP
						INNER JOIN LOS_SELECTOS.BI_MEDIO_DE_PAGO MDP ON VP.MEDIO_DE_PAGO_CODIGO = MDP.MEDIO_DE_PAGO_CODIGO
						INNER JOIN LOS_SELECTOS.BI_TIEMPO T1 ON VP.TIEMPO_CODIGO = T1.TIEMPO_CODIGO
						INNER JOIN LOS_SELECTOS.BI_CANAL_VENTA CV1 ON VP.CANAL_CODIGO = CV1.CANAL_CODIGO
						WHERE T1.TIEMPO_ANIO = T.TIEMPO_ANIO AND T1.TIEMPO_MES = T.TIEMPO_MES
						AND CV1.CANAL_NOMBRE = CV.CANAL_NOMBRE
					  ) VENTA_PERIODICIDAD
		) COSTOS_DE_MEDIO_DE_PAGO,
		SUM(HVP.PRODUCTO_PRECIO_TOTAL)
		- SUM(HCP.PRODUCTO_CANTIDAD*HCP.PRODUCTO_PRECIO_UNITARIO)
		- (SELECT SUM(VENTA_PERIODICIDAD.MEDIO_DE_PAGO_COSTO)
						FROM (SELECT MDP.MEDIO_DE_PAGO_COSTO
								FROM LOS_SELECTOS.BI_HECHO_VENTA_PRODUCTO VP
								INNER JOIN LOS_SELECTOS.BI_MEDIO_DE_PAGO MDP ON VP.MEDIO_DE_PAGO_CODIGO = MDP.MEDIO_DE_PAGO_CODIGO
								INNER JOIN LOS_SELECTOS.BI_TIEMPO T1 ON VP.TIEMPO_CODIGO = T1.TIEMPO_CODIGO
								INNER JOIN LOS_SELECTOS.BI_CANAL_VENTA CV1 ON VP.CANAL_CODIGO = CV1.CANAL_CODIGO
								WHERE T1.TIEMPO_ANIO = T.TIEMPO_ANIO AND T1.TIEMPO_MES = T.TIEMPO_MES
								AND CV1.CANAL_NOMBRE = CV.CANAL_NOMBRE
							  ) VENTA_PERIODICIDAD
		  ) AS GANANCIA
		FROM LOS_SELECTOS.BI_HECHO_VENTA_PRODUCTO HVP
		JOIN LOS_SELECTOS.BI_PRODUCTO P ON P.PRODUCTO_CODIGO = HVP.PRODUCTO_CODIGO
		JOIN LOS_SELECTOS.BI_HECHO_COMPRA_PRODUCTO HCP ON HCP.PRODUCTO_CODIGO = P.PRODUCTO_CODIGO
		JOIN LOS_SELECTOS.BI_TIEMPO T ON T.TIEMPO_CODIGO = HVP.TIEMPO_CODIGO OR HCP.TIEMPO_CODIGO = T.TIEMPO_CODIGO
		JOIN LOS_SELECTOS.BI_CANAL_VENTA CV ON CV.CANAL_CODIGO = HVP.CANAL_CODIGO
		JOIN LOS_SELECTOS.BI_MEDIO_DE_PAGO MP ON MP.MEDIO_DE_PAGO_CODIGO = HVP.MEDIO_DE_PAGO_CODIGO
		GROUP BY T.TIEMPO_ANIO, T.TIEMPO_MES, CV.CANAL_NOMBRE
GO

