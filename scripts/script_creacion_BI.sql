				JOIN LOS_SELECTOS.BI_TIEMPO T ON T.TIEMPO_ANIO = year(V.VENTA_FECHA) AND T.TIEMPO_MES = month(V.VENTA_FECHA)
			) VISTA
			GROUP BY 
