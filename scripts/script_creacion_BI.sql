			ORDER BY VISTA.TIEMPO_CODIGO, VISTA.PROVINCIA_CODIGO, VISTA.MEDIO_ENVIO_CODIGO
	DECLARE @CANTIDAD_REGISTROS NVARCHAR(255)
	SET @CANTIDAD_REGISTROS = (SELECT COUNT(*) FROM LOS_SELECTOS.BI_HECHO_VENTA_PRODUCTO)
