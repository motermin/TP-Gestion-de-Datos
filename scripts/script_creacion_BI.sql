					INNER JOIN LOS_SELECTOS.MEDIO_ENVIO ME ON ME.MEDIO_ENVIO_CODIGO = VMEPL.MEDIO_ENVIO_CODIGO
					INNER JOIN LOS_SELECTOS.BI_MEDIO_DE_ENVIO BI_ME ON BI_ME.MEDIO_ENVIO_NOMBRE = ME.MEDIO_ENVIO_NOMBRE
					WHERE 
					T.TIEMPO_CODIGO = VISTA.TIEMPO_CODIGO AND
					BI_P.PROVINCIA_CODIGO = VISTA.PROVINCIA_CODIGO AND
					BI_ME.MEDIO_ENVIO_CODIGO = VISTA.MEDIO_ENVIO_CODIGO
